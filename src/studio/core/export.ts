import { compileProject } from './compiler.ts';
import { validateProject } from './project.ts';
import type { Project } from './types.ts';

/**
 * Standalone export has explicit render settings. Internal render jobs keep using
 * compileProject() so worker-selected preview resolution and cache keys remain intact.
 */
export function exportStandalonePython(input: Project | unknown): string {
  const project = validateProject(input);
  const compiled = compileProject(project);
  const errors = compiled.diagnostics.filter((diagnostic) => diagnostic.severity === 'error');
  if (errors.length) throw new Error(errors.map((diagnostic) => diagnostic.message).join('\n'));
  const importLine = 'from manim import *\n';
  if (!compiled.code.startsWith(importLine)) throw new Error('无法定位 Manim 导入语句，源码导出已停止。');
  const { width, height, fps } = project.scene;
  const header = [
    '# Generated by AnyVis. This file includes the project\'s output settings.',
    '# Run: python -m manim render --format webm your_scene.py AnyVisScene',
    '# Use --format mp4 if the local PyAV build includes libx264.',
    '# AnyVis can transcode WebM to MP4 when libx264 is unavailable; this file',
    '# uses the native Manim CLI and does not install or replace any codecs.',
    '# Keep the same Manim version, fonts and formula tools for reproducible output.',
    ...(compiled.requiresTrust ? ['# WARNING: this project contains Python extensions or privileged API calls with local system access.'] : []),
  ].join('\n');
  const settings = [
    '# Explicit project output settings, matching the AnyVis worker.',
    `config.renderer = "${project.scene.renderer || 'cairo'}"`,
    `config.pixel_width = ${width}`,
    `config.pixel_height = ${height}`,
    `config.frame_height = 8`,
    `config.frame_width = 8 * (${width} / ${height})`,
    `config.frame_rate = ${fps}`,
    '',
  ].join('\n');
  return `${header}\n${importLine}${settings}\n${compiled.code.slice(importLine.length)}`;
}
