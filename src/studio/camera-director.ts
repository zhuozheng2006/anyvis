/** Standard Manim 16:9 frame dimensions at zoom=1 */
export const BASE_FRAME_WIDTH = 14.22;
export const BASE_FRAME_HEIGHT = 8.0;

/** Computes the mathematical boundary coordinates of the camera viewfinder box */
export function getViewfinderBox(x: number, y: number, zoom: number): ViewfinderBox {
  const safeZoom = Math.max(0.2, Math.min(10.0, zoom));
  const width = BASE_FRAME_WIDTH / safeZoom;
  const height = BASE_FRAME_HEIGHT / safeZoom;

  return {
    left: x - width / 2,
    right: x + width / 2,
    top: y + height / 2,
    bottom: y - height / 2,
    width,
    height,
  };
}

/** Interpolates camera pose between shots at time t */
export function interpolateCameraPose(shots: CameraShot[], t: number): { x: number; y: number; zoom: number } {
  if (shots.length === 0) return { x: 0, y: 0, zoom: 1.0 };
  const sorted = [...shots].sort((a, b) => a.time - b.time);

  if (t <= sorted[0].time) {
    return { x: sorted[0].x, y: sorted[0].y, zoom: sorted[0].zoom };
  }
  if (t >= sorted[sorted.length - 1].time) {
    const last = sorted[sorted.length - 1];
    return { x: last.x, y: last.y, zoom: last.zoom };
  }

  // Find surrounding shots
  for (let i = 0; i < sorted.length - 1; i++) {
    const curr = sorted[i];
    const next = sorted[i + 1];

    if (t >= curr.time && t <= next.time) {
      const transStart = next.time - next.duration;
      if (t < transStart) {
        return { x: curr.x, y: curr.y, zoom: curr.zoom };
      }
      // Ease progress
      const p = Math.max(0, Math.min(1, (t - transStart) / next.duration));
      // smoothstep easing
      const eased = p * p * (3 - 2 * p);

      return {
        x: curr.x + (next.x - curr.x) * eased,
        y: curr.y + (next.y - curr.y) * eased,
        zoom: curr.zoom + (next.zoom - curr.zoom) * eased,
      };
    }
  }

  const last = sorted[sorted.length - 1];
  return { x: last.x, y: last.y, zoom: last.zoom };
}

/** Generates runnable Manim CE Python code for MovingCameraScene */
export function generateCameraDirectorPythonCode(shots: CameraShot[]): string {
  const sorted = [...shots].sort((a, b) => a.time - b.time);
  const movements = sorted.slice(1).map((shot, idx) => {
    const targetWidth = (BASE_FRAME_WIDTH / shot.zoom).toFixed(2);
    return `        # --- Shot ${idx + 2}: ${shot.name} ---
        self.play(
            self.camera.frame.animate.move_to([${shot.x.toFixed(2)}, ${shot.y.toFixed(2)}, 0]).set(width=${targetWidth}),
            run_time=${shot.duration.toFixed(1)},
            rate_func=${shot.rateFunc},
        )
        self.wait(1.5)`;
  }).join('\n\n');

  return `# Auto-generated by AnyVis - Motion Canvas Style MovingCameraScene
from manim import *

class CinematicCameraScene(MovingCameraScene):
    def construct(self):
        # Demo Scene Elements
        title = Title(r"Cinematic Camera Director", color=GOLD)
        grid = NumberPlane().set_opacity(0.35)
        dot_left = Dot([-2.4, 0.8, 0], color=TEAL, radius=0.2)
        dot_right = Dot([2.4, -0.5, 0], color=RED, radius=0.2)
        lbl_left = Text("Subject A", font_size=20, color=TEAL).next_to(dot_left, DOWN)
        lbl_right = Text("Subject B", font_size=20, color=RED).next_to(dot_right, DOWN)

        self.play(Write(title), Create(grid))
        self.play(FadeIn(dot_left), FadeIn(lbl_left), FadeIn(dot_right), FadeIn(lbl_right))
        self.wait(1.0)

${movements}
`;
}

/** Injects camera director metadata and actions into project */
export function createCameraDirectorActions(
  project: Project,
  shots: CameraShot[],
): { project: Project; actionIds: string[] } {
  const ts = Date.now();
  const sorted = [...shots].sort((a, b) => a.time - b.time);

  const actions: Action[] = sorted.map((shot, idx) => ({
    id: `action_camshot_${idx}_${ts}`,
    type: 'camera_move',
    fields: {
      name: shot.name,
      startTime: shot.time,
      runTime: shot.duration,
      targetX: shot.x,
      targetY: shot.y,
      zoom: shot.zoom,
      rateFunc: shot.rateFunc,
    },
    children: [],
  }));

  return {
    project: {
      ...project,
      actions: [...project.actions, ...actions],
    },
    actionIds: actions.map((a) => a.id),
  };
}
