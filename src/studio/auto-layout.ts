import type { Action, Project } from './core/types';
import { flattenActions } from './authoring';
import { getBlockDefinition } from './core/catalog';

export type LayoutMode =
  | 'horizontal'
  | 'vertical'
  | 'grid'
  | 'radial'
  | 'distribute_h'
  | 'distribute_v';

export interface LayoutConfig {
  mode: LayoutMode;
  gap: number;
  cols?: number;
  rowGap?: number;
  colGap?: number;
  radius?: number;
  startAngleDeg?: number;
  anchorCenter?: [number, number];
}

export interface MovableObject {
  actionId: string;
  name: string;
  type: string;
  x: number;
  y: number;
}

/** Extracts all movable objects (actions with x and y coordinates) from project */
export function getMovableObjects(project: Project): MovableObject[] {
  const movables: MovableObject[] = [];

  for (const act of flattenActions(project.actions)) {
    if (
      getBlockDefinition(act.type)?.createsObject &&
      act.fields &&
      typeof act.fields.x === 'number' &&
      typeof act.fields.y === 'number'
    ) {
      const name =
        typeof act.fields.name === 'string' && act.fields.name.trim()
          ? act.fields.name
          : act.id;
      movables.push({
        actionId: act.id,
        name,
        type: act.type,
        x: act.fields.x,
        y: act.fields.y,
      });
    }
  }

  return movables;
}

/** Computes new (x, y) coordinates for target objects according to layout rules */
export function computeLayoutPositions(
  objects: MovableObject[],
  config: LayoutConfig,
): Map<string, [number, number]> {
  const result = new Map<string, [number, number]>();
  const n = objects.length;
  if (n === 0) return result;

  // Default anchor is the centroid of selected objects
  let cx = 0;
  let cy = 0;
  if (config.anchorCenter) {
    [cx, cy] = config.anchorCenter;
  } else {
    cx = objects.reduce((sum, o) => sum + o.x, 0) / n;
    cy = objects.reduce((sum, o) => sum + o.y, 0) / n;
  }

  if (config.mode === 'horizontal') {
    const gap = config.gap ?? 1.0;
    const totalW = (n - 1) * gap;
    objects.forEach((obj, idx) => {
      const newX = Number((cx - totalW / 2 + idx * gap).toFixed(2));
      const newY = Number(cy.toFixed(2));
      result.set(obj.actionId, [newX, newY]);
    });
  } else if (config.mode === 'vertical') {
    const gap = config.gap ?? 0.8;
    const totalH = (n - 1) * gap;
    objects.forEach((obj, idx) => {
      const newX = Number(cx.toFixed(2));
      const newY = Number((cy + totalH / 2 - idx * gap).toFixed(2));
      result.set(obj.actionId, [newX, newY]);
    });
  } else if (config.mode === 'grid') {
    const cols = Math.max(1, config.cols ?? 2);
    const rows = Math.ceil(n / cols);
    const colGap = config.colGap ?? config.gap ?? 1.2;
    const rowGap = config.rowGap ?? config.gap ?? 1.0;

    const totalW = (cols - 1) * colGap;
    const totalH = (rows - 1) * rowGap;

    objects.forEach((obj, idx) => {
      const r = Math.floor(idx / cols);
      const c = idx % cols;
      const newX = Number((cx - totalW / 2 + c * colGap).toFixed(2));
      const newY = Number((cy + totalH / 2 - r * rowGap).toFixed(2));
      result.set(obj.actionId, [newX, newY]);
    });
  } else if (config.mode === 'radial') {
    const radius = config.radius ?? 2.0;
    const startAngle = ((config.startAngleDeg ?? 90) * Math.PI) / 180;
    const angleStep = (2 * Math.PI) / n;

    objects.forEach((obj, idx) => {
      const angle = startAngle + idx * angleStep;
      const newX = Number((cx + radius * Math.cos(angle)).toFixed(2));
      const newY = Number((cy + radius * Math.sin(angle)).toFixed(2));
      result.set(obj.actionId, [newX, newY]);
    });
  } else if (config.mode === 'distribute_h') {
    if (n <= 2) {
      objects.forEach((obj) => result.set(obj.actionId, [obj.x, obj.y]));
      return result;
    }
    const sorted = [...objects].sort((a, b) => a.x - b.x);
    const minX = sorted[0].x;
    const maxX = sorted[n - 1].x;
    const step = (maxX - minX) / (n - 1);

    sorted.forEach((obj, idx) => {
      const newX = Number((minX + idx * step).toFixed(2));
      result.set(obj.actionId, [newX, obj.y]);
    });
  } else if (config.mode === 'distribute_v') {
    if (n <= 2) {
      objects.forEach((obj) => result.set(obj.actionId, [obj.x, obj.y]));
      return result;
    }
    const sorted = [...objects].sort((a, b) => b.y - a.y);
    const maxY = sorted[0].y;
    const minY = sorted[n - 1].y;
    const step = (maxY - minY) / (n - 1);

    sorted.forEach((obj, idx) => {
      const newY = Number((maxY - idx * step).toFixed(2));
      result.set(obj.actionId, [obj.x, newY]);
    });
  }

  return result;
}

/** Generates idiomatic Manim CE VGroup arrangement Python code */
export function generateAutoLayoutPythonCode(
  objects: MovableObject[],
  config: LayoutConfig,
): string {
  const names = objects.map((o) => o.name);
  const mobList = names.join(', ');

  if (config.mode === 'horizontal') {
    return `# Auto-generated by AnyVis - Manim VGroup Horizontal Arrangement
from manim import *

class LayoutScene(Scene):
    def construct(self):
        # Assume objects exist: ${mobList}
        group = VGroup(${mobList})
        group.arrange(RIGHT, buff=${(config.gap ?? 1.0).toFixed(2)})
        self.play(Create(group))
        self.wait()
`;
  }

  if (config.mode === 'vertical') {
    return `# Auto-generated by AnyVis - Manim VGroup Vertical Arrangement
from manim import *

class LayoutScene(Scene):
    def construct(self):
        # Assume objects exist: ${mobList}
        group = VGroup(${mobList})
        group.arrange(DOWN, buff=${(config.gap ?? 0.8).toFixed(2)})
        self.play(Create(group))
        self.wait()
`;
  }

  if (config.mode === 'grid') {
    const cols = config.cols ?? 2;
    const rows = Math.ceil(objects.length / cols);
    return `# Auto-generated by AnyVis - Manim Grid Layout
from manim import *

class LayoutScene(Scene):
    def construct(self):
        group = VGroup(${mobList})
        group.arrange_in_grid(
            rows=${rows},
            cols=${cols},
            buff=(${(config.colGap ?? config.gap ?? 1.2).toFixed(2)}, ${(config.rowGap ?? config.gap ?? 1.0).toFixed(2)})
        )
        self.play(Create(group))
        self.wait()
`;
  }

  if (config.mode === 'radial') {
    return `# Auto-generated by AnyVis - Manim Radial Layout
import numpy as np
from manim import *

class LayoutScene(Scene):
    def construct(self):
        items = [${mobList}]
        radius = ${(config.radius ?? 2.0).toFixed(2)}
        n = len(items)
        start_angle = np.deg2rad(${(config.startAngleDeg ?? 90).toFixed(1)})

        for i, mob in enumerate(items):
            angle = start_angle + i * (2 * np.pi / n)
            target_pos = np.array([radius * np.cos(angle), radius * np.sin(angle), 0])
            mob.move_to(target_pos)

        self.play(LaggedStart(*[FadeIn(m) for m in items], lag_ratio=0.15))
        self.wait()
`;
  }

  return `# Auto-generated by AnyVis - Manim Distributed Layout
from manim import *

class LayoutScene(Scene):
    def construct(self):
        group = VGroup(${mobList})
        group.arrange(RIGHT, buff=0.8)
        self.play(Create(group))
        self.wait()
`;
}

/** Applies updated positions to the project actions */
export function applyLayoutToProject(
  project: Project,
  newPositions: Map<string, [number, number]>,
): Project {
  const apply = (actions: Action[]): Action[] => actions.map((act) => {
    if (newPositions.has(act.id)) {
      const [newX, newY] = newPositions.get(act.id)!;
      return {
        ...act,
        fields: {
          ...act.fields,
          x: newX,
          y: newY,
        },
      };
    }
    return { ...act, ...(act.children ? { children: apply(act.children) } : {}), ...(act.branches ? { branches: act.branches.map(apply) } : {}) };
  });

  return {
    ...project,
    workspace: undefined,
    actions: apply(project.actions),
  };
}
