/** Formats seconds to SRT timestamp 00:00:00,000 */
export function formatSrtTime(seconds: number): string {
  const safe = Math.max(0, seconds);
  const totalMs = Math.round(safe * 1000);
  const hrs = Math.floor(totalMs / 3600000);
  const mins = Math.floor((totalMs % 3600000) / 60000);
  const secs = Math.floor((totalMs % 60000) / 1000);
  const ms = totalMs % 1000;

  return `${hrs.toString().padStart(2, '0')}:${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')},${ms.toString().padStart(3, '0')}`;
}

/** Parses SRT timestamp 00:00:00,000 to seconds */
export function parseSrtTime(stamp: string): number {
  const clean = stamp.trim().replace('.', ',');
  const parts = clean.split(':');
  if (parts.length < 3) return 0;
  const hrs = parseFloat(parts[0]) || 0;
  const mins = parseFloat(parts[1]) || 0;
  const secParts = parts[2].split(',');
  const secs = parseFloat(secParts[0]) || 0;
  const ms = parseFloat(secParts[1]) || 0;
  return hrs * 3600 + mins * 60 + secs + ms / 1000;
}

/** Exports subtitles to standard SRT file format */
export function exportToSrt(subtitles: SubtitleItem[]): string {
  const sorted = [...subtitles].sort((a, b) => a.startTime - b.startTime);
  return sorted
    .map((sub, idx) => {
      return `${idx + 1}\n${formatSrtTime(sub.startTime)} --> ${formatSrtTime(sub.endTime)}\n${sub.text.trim()}\n`;
    })
    .join('\n');
}

/** Parses standard SRT string into SubtitleItem list */
export function parseSrt(srtContent: string): SubtitleItem[] {
  const blocks = srtContent.trim().split(/\n\s*\n/);
  const items: SubtitleItem[] = [];

  for (let i = 0; i < blocks.length; i++) {
    const lines = blocks[i].trim().split('\n');
    if (lines.length < 2) continue;

    const timeLine = lines.find((l) => l.includes('-->'));
    if (!timeLine) continue;

    const [startStr, endStr] = timeLine.split('-->');
    const startTime = parseSrtTime(startStr);
    const endTime = parseSrtTime(endStr);

    const timeLineIdx = lines.indexOf(timeLine);
    const textLines = lines.slice(timeLineIdx + 1).join(' ').trim();

    if (textLines) {
      items.push({
        id: `sub_${Date.now()}_${i}`,
        startTime: Number(startTime.toFixed(2)),
        endTime: Number(endTime.toFixed(2)),
        text: textLines,
        color: '#ffffff',
        fontSize: 24,
        position: 'bottom',
      });
    }
  }

  return items;
}

/** Generates runnable Manim CE Python code for subtitle sync */
export function generateSubtitlesPythonCode(subtitles: SubtitleItem[]): string {
  const sorted = [...subtitles].sort((a, b) => a.startTime - b.startTime);
  const captionsCode = sorted
    .map((sub, idx) => {
      const duration = (sub.endTime - sub.startTime).toFixed(1);
      const colorHex = sub.color || '#ffffff';
      const colorVal =
        colorHex.toLowerCase() === '#58c4dd'
          ? 'TEAL'
          : colorHex.toLowerCase() === '#e2b340'
          ? 'GOLD'
          : colorHex.toLowerCase() === '#83c167'
          ? 'GREEN'
          : 'WHITE';

      return `        # Caption ${idx + 1} (${sub.startTime}s - ${sub.endTime}s)
        sub_${idx} = Text("${sub.text}", font_size=${sub.fontSize || 24}, color=${colorVal}).to_edge(DOWN, buff=0.8)
        self.play(FadeIn(sub_${idx}, shift=0.2 * UP), run_time=0.4)
        self.wait(${Math.max(0.2, parseFloat(duration) - 0.8).toFixed(1)})
        self.play(FadeOut(sub_${idx}), run_time=0.4)`;
    })
    .join('\n\n');

  return `# Auto-generated by AnyVis - Remotion Style Subtitle Sync
from manim import *

class SubtitleNarrationScene(Scene):
    def construct(self):
        title = Title(r"Narration & Subtitle Sync Demo", color=GOLD)
        self.add(title)
        self.wait(0.5)

${captionsCode}
`;
}

/** Injects timed subtitle text actions into project */
export function createSubtitleActions(
  project: Project,
  subtitles: SubtitleItem[],
): { project: Project; actionIds: string[] } {
  const ts = Date.now();
  const sorted = [...subtitles].sort((a, b) => a.startTime - b.startTime);

  const actions: Action[] = sorted.map((sub, idx) => ({
    id: `action_sub_${idx}_${ts}`,
    type: 'create_text',
    fields: {
      name: `sub_line_${idx + 1}`,
      text: sub.text,
      startTime: sub.startTime,
      runTime: Number((sub.endTime - sub.startTime).toFixed(2)),
      color: sub.color || '#ffffff',
      fontSize: sub.fontSize || 24,
      x: 0,
      y: sub.position === 'top' ? 3.0 : sub.position === 'center' ? 0 : -3.2,
    },
    children: [],
  }));

  return {
    project: {
      ...project,
      actions: [...project.actions, ...actions],
    },
    actionIds: actions.map((a) => a.id),
  };
}
