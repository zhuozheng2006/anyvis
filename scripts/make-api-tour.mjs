#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createAction} from '../src/studio/core/catalog.ts';
import {getApiEntry} from '../src/studio/core/api-registry.ts';
import {compileProject} from '../src/studio/core/compiler.ts';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
let index=0;const actions=[];
const add=(type,fields)=>{const action=createAction(type,fields);action.id=`api-tour-${++index}`;actions.push(action);return action;};
const api=(name,result,parameters={},fields={})=>add(getApiEntry(name).type,{name:result,...Object.fromEntries(Object.entries(parameters).map(([k,v])=>[`p_${k}`,JSON.stringify(v)])),...fields});
const ref=name=>({$ref:name});
const text=(name,content,y,fontSize=25,color='#E5EDF8')=>add('text',{name,text:content,y,fontSize,color,appear:'fade',duration:0.6,maxWidth:12});
text('标题','一个参数，怎样改变整条曲线？',3.15,34);
text('副标题','y = a · sin(x)　｜　把对象、方法和回调函数连接起来',2.5,20,'#8494AF');
add('axes',{name:'坐标系',xMin:-3.5,xMax:3.5,yMin:-2.2,yMax:2.2,xLength:9,yLength:4,y:-0.3,color:'#40516C',duration:1});
add('tracker',{name:'a',value:1});
const plot={$call:{api:'CoordinateSystem.plot',receiver:ref('坐标系'),args:[{$lambda:{params:['x'],body:{$expr:'a*sin(x)'}}}],kwargs:{x_range:[-3.14,3.14],color:'#64D9C1',stroke_width:4}}};
api('always_redraw','变化的曲线',{func:{$lambda:{params:[],body:plot}}},{mode:'store'});
api('Create','画出曲线',{mobject:ref('变化的曲线')},{duration:1.5});
text('参数名','a =',1.7,24,'#F2CB80');
add('move',{target:'参数名',x:4.7,y:1.7,duration:0.3});
add('dynamic_number',{name:'参数读数',parameter:'a',x:5.5,y:1.7,fontSize:27,color:'#F2CB80',places:2,duration:0.5});
text('说明一','增大 a：横坐标不动，高度按同一比例放大。',-2.9,24);
api('ValueTracker.set_value','放大振幅',{value:2},{receiver:'a',mode:'animate',duration:4});
add('wait',{duration:1});
add('fade_out',{target:'说明一',duration:0.4});
text('说明二','减小 a：波峰与波谷一起靠近横轴，周期保持不变。',-2.9,24);
api('ValueTracker.set_value','减小振幅',{value:0.4},{receiver:'a',mode:'animate',duration:4});
add('wait',{duration:1});
add('fade_out',{target:'说明二',duration:0.4});
text('说明三','函数规则没有换；动画来自同一个参数的连续变化。',-2.9,24);
api('ValueTracker.set_value','回到单位振幅',{value:1},{receiver:'a',mode:'animate',duration:3});
text('结语','每一个步骤，仍然可以打开积木修改。',-3.5,19,'#8494AF');
add('wait',{duration:2});
const project={schemaVersion:2,id:'anyvis-api-tour',name:'API 积木 · 一个参数改变整条曲线',scene:{dimension:'2d',background:'#0B1020',width:1280,height:720,fps:24},actions};
const compiled=compileProject(project);const errors=compiled.diagnostics.filter(d=>d.severity==='error');if(errors.length)throw Error(JSON.stringify(errors));
if(compiled.requiresTrust)throw Error('The tour must remain a native, unprivileged project.');
fs.mkdirSync(path.join(root,'examples/api'),{recursive:true});fs.writeFileSync(path.join(root,'examples/api/parameter-curve.anyvis.json'),JSON.stringify(project,null,2)+'\n');
console.log(`Created ${actions.length} editable blocks, ${compiled.duration.toFixed(1)} seconds.`);
